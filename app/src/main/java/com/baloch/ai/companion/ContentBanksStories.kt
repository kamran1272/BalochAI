/**
 * Picks random items from banks without repeating the same item twice
 * in a row. Each bank has its own key so histories don't collide.
 * Thread-safe for use from coroutines.
 */
object CompanionPicker {
    private val lastIndex = mutableMapOf<String, Int>()

    @Synchronized
    fun <T> pick(key: String, items: List<T>): T {
        require(items.isNotEmpty()) { "CompanionPicker: empty bank for key=$key" }
        if (items.size == 1) return items[0]
        val last = lastIndex[key]
        var idx: Int
        do {
            idx = (0 until items.size).random()
        } while (idx == last)
        lastIndex[key] = idx
        return items[idx]
    }

    /** Convenience: pick an [L3] and resolve it to the active language. */
    @Synchronized
    fun pickL3(key: String, items: List<L3>, lang: com.baloch.ai.brain.BalochLanguage): String =
        pick(key, items).pick(lang)

    @Synchronized
    fun reset(key: String) {
        lastIndex.remove(key)
    }
}
